package net.arcanic.visuals.arc;

public class GeoVec {
    public static final GeoVec ZERO = new GeoVec(0, 0, 0);
    public float x;
    public float y;
    public float z;

    public GeoVec(float x, float y, float z) {
        this.x = x;
        this.y = y;
        this.z = z;
    }

    public float getX() {
        return x;
    }

    public float getY() {
        return y;
    }

    public float getZ() {
        return z;
    }

    public void set(float x, float y, float z) {
        this.x = x;
        this.y = y;
        this.z = z;
    }

    @Override
    public String toString() {
        return x + ", " + y + ", " + z;
    }
}
