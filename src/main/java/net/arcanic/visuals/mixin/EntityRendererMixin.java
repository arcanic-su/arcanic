package net.arcanic.visuals.mixin;

import com.mojang.blaze3d.vertex.PoseStack;
import net.arcanic.visuals.core.Modules;
import net.arcanic.visuals.fx.Ducks;
import net.minecraft.client.renderer.SubmitNodeCollector;
import net.minecraft.client.renderer.entity.EntityRenderer;
import net.minecraft.client.renderer.entity.state.EntityRenderState;
import net.minecraft.client.renderer.state.CameraRenderState;
import net.minecraft.world.entity.Entity;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

@Mixin(EntityRenderer.class)
public abstract class EntityRendererMixin {
    @Inject(method = "submitNameTag", at = @At("HEAD"), cancellable = true)
    private void arcanic$customName(
            EntityRenderState state,
            PoseStack pose,
            SubmitNodeCollector collector,
            CameraRenderState camera,
            CallbackInfo ci) {
        if (Modules.NAMETAGS.replaces(Ducks.entityOf(state))) ci.cancel();
    }

    @Inject(
            method =
                    "createRenderState(Lnet/minecraft/world/entity/Entity;F)Lnet/minecraft/client/renderer/entity/state/EntityRenderState;",
            at = @At("RETURN"))
    private void arcanicvisuals$link(Entity entity, float partialTick, CallbackInfoReturnable<EntityRenderState> cir) {
        if (cir.getReturnValue() instanceof Ducks.EntityLink l) l.arcanicvisuals$setEntity(entity);
    }
}
