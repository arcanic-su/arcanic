package net.arcanic.visuals.mixin;

import net.arcanic.visuals.core.Modules;
import net.minecraft.client.gui.Gui;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.ModifyArg;

/** The hotbar's selection frame slides to the picked slot (Анимации интерфейса). */
@Mixin(Gui.class)
public abstract class UiAnimationsMixin {
    @ModifyArg(
            method = "renderItemHotbar",
            at =
                    @At(
                            value = "INVOKE",
                            target =
                                    "Lnet/minecraft/client/gui/GuiGraphics;blitSprite(Lcom/mojang/blaze3d/pipeline/RenderPipeline;Lnet/minecraft/resources/Identifier;IIII)V",
                            ordinal = 1),
            index = 2,
            require = 0)
    private int arcanicvisuals$slideSelection(int x) {
        return Modules.UI_ANIMATIONS.hotbarX(x);
    }
}
