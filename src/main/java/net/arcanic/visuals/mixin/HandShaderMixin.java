package net.arcanic.visuals.mixin;

import net.arcanic.visuals.arc.HandShaders;
import net.minecraft.client.renderer.GameRenderer;
import org.joml.Matrix4f;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.*;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(GameRenderer.class)
public abstract class HandShaderMixin {
    @Inject(
            method = "renderItemInHand",
            at =
                    @At(
                            value = "INVOKE",
                            target =
                                    "Lnet/minecraft/client/renderer/ItemInHandRenderer;renderHandsWithItems(FLcom/mojang/blaze3d/vertex/PoseStack;Lnet/minecraft/client/renderer/SubmitNodeCollector;Lnet/minecraft/client/player/LocalPlayer;I)V"))
    private void begin(float tick, boolean sleeping, Matrix4f view, CallbackInfo ci) {
        HandShaders.begin();
    }

    @Inject(method = "renderItemInHand", at = @At("RETURN"))
    private void end(float tick, boolean sleeping, Matrix4f view, CallbackInfo ci) {
        HandShaders.finish();
    }
}
