package net.arcanic.visuals.mixin;

import net.arcanic.visuals.fx.Ducks;
import net.minecraft.client.renderer.entity.state.EntityRenderState;
import net.minecraft.world.entity.Entity;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Unique;

/** Remembers which entity a render state was made from. */
@Mixin(EntityRenderState.class)
public abstract class EntityRenderStateMixin implements Ducks.EntityLink {
    @Unique
    private Entity arcanicvisuals$entity;

    @Override
    public Entity arcanicvisuals$entity() {
        return arcanicvisuals$entity;
    }

    @Override
    public void arcanicvisuals$setEntity(Entity e) {
        arcanicvisuals$entity = e;
    }
}
