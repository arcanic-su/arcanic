package net.arcanic.visuals.mixin;

import net.arcanic.visuals.core.Modules;
import net.minecraft.client.multiplayer.MultiPlayerGameMode;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.inventory.ClickType;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** Lock Slot: a locked item thrown from an open inventory stays where it is. */
@Mixin(MultiPlayerGameMode.class)
public abstract class LockSlotMixin {
    @Inject(method = "handleInventoryMouseClick", at = @At("HEAD"), cancellable = true)
    private void arcanicvisuals$keepLocked(
            int containerId, int slotId, int button, ClickType type, Player player, CallbackInfo ci) {
        if (Modules.LOCK_SLOT.blocksThrow(slotId, type)) ci.cancel();
    }
}
